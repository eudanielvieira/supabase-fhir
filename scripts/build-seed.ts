#!/usr/bin/env bun
/**
 * Regenerates supabase/seeds/*.sql from a Synthea output directory.
 *
 *   bun run seed:build --dir ./data/synthea/fhir --patients 4
 *
 * Picks the smallest patient bundles above --min-kb, trims the provider bundles to the
 * organizations, locations and practitioners those patients reference, and writes:
 *   10_synthea_providers.sql  organizations, locations, practitioners, roles
 *   20_synthea_patients.sql   one import_bundle call per patient
 *   30_demo_users.sql         three demo logins wired to the seeded patients
 */
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import type { Bundle, BundleEntry, Identifier } from 'fhir/r4';

const { values } = parseArgs({
  args: Bun.argv.slice(2),
  options: {
    dir: { type: 'string', default: 'data/synthea/fhir' },
    patients: { type: 'string', default: '4' },
    'min-kb': { type: 'string', default: '120' },
    out: { type: 'string', default: 'supabase/seeds' },
  },
});

const dir = values.dir!;
const out = values.out!;
const wanted = Number.parseInt(values.patients!, 10);
const minBytes = Number.parseInt(values['min-kb']!, 10) * 1024;

const isProvider = (name: string) => /^(hospital|practitioner)Information/.test(name);
const names = (await readdir(dir)).filter((n) => n.endsWith('.json'));
const sized = await Promise.all(names.map(async (name) => ({ name, size: (await stat(join(dir, name))).size })));
const providerFiles = sized.filter((f) => isProvider(f.name)).map((f) => f.name);
const patientFiles = sized
  .filter((f) => !isProvider(f.name) && f.size >= minBytes)
  .sort((a, b) => a.size - b.size)
  .slice(0, wanted)
  .map((f) => f.name);

if (providerFiles.length === 0 || patientFiles.length === 0) {
  console.error(`no bundles found in ${dir}`);
  process.exit(1);
}

const readBundle = async (name: string) => (await Bun.file(join(dir, name)).json()) as Bundle;
const patientBundles = await Promise.all(patientFiles.map(readBundle));
const providerBundles = await Promise.all(providerFiles.map(readBundle));

// Identifiers referenced by the chosen patients, as 'Type|system|value'.
const referenced = new Set<string>();
const collect = (value: unknown) => {
  if (Array.isArray(value)) return value.forEach(collect);
  if (!value || typeof value !== 'object') return;
  for (const [key, inner] of Object.entries(value as Record<string, unknown>)) {
    if (key === 'reference' && typeof inner === 'string') {
      const match = /^([A-Z][A-Za-z]+)\?identifier=([^|]*)\|(.+)$/.exec(inner);
      if (match) referenced.add(`${match[1]}|${match[2]}|${match[3]}`);
    } else {
      collect(inner);
    }
  }
};
patientBundles.forEach(collect);

const key = (type: string, identifier: Identifier) => `${type}|${identifier.system ?? ''}|${identifier.value ?? ''}`;
const matches = (entry: BundleEntry) => {
  const resource = entry.resource as { resourceType: string; identifier?: Identifier[] } | undefined;
  return resource?.identifier?.some((id) => referenced.has(key(resource.resourceType, id))) ?? false;
};

// Keep referenced providers, then the roles of the kept practitioners (logical references by identifier).
const keptPractitioners = new Set<string>();
const trimmed: BundleEntry[] = [];
for (const bundle of providerBundles) {
  for (const entry of bundle.entry ?? []) {
    if (!matches(entry)) continue;
    trimmed.push(entry);
    const resource = entry.resource as { resourceType: string; identifier?: Identifier[] };
    if (resource.resourceType === 'Practitioner') {
      for (const id of resource.identifier ?? []) keptPractitioners.add(`${id.system ?? ''}|${id.value ?? ''}`);
    }
  }
}
for (const bundle of providerBundles) {
  for (const entry of bundle.entry ?? []) {
    const resource = entry.resource as { resourceType: string; practitioner?: { identifier?: Identifier } } | undefined;
    const id = resource?.practitioner?.identifier;
    if (resource?.resourceType === 'PractitionerRole' && id && keptPractitioners.has(`${id.system ?? ''}|${id.value ?? ''}`)) {
      trimmed.push(entry);
    }
  }
}

const providersBundle: Bundle = { resourceType: 'Bundle', type: 'batch', entry: trimmed };

const sqlFor = (bundle: Bundle) => {
  const json = JSON.stringify(bundle);
  if (json.includes('$synthea$')) throw new Error('bundle contains the dollar-quote tag');
  return `select fhir.import_bundle($synthea$${json}$synthea$::jsonb);\n`;
};

const header = (what: string) =>
  `-- ${what}\n-- Generated by scripts/build-seed.ts from Synthea synthetic data (https://synthea.mitre.org). Do not edit by hand.\n-- Synthetic patients only: there is no real patient data anywhere in this repository.\n\n`;

const patientIds = patientBundles.map((b) => {
  const entry = b.entry?.find((e) => e.resource?.resourceType === 'Patient');
  const resource = entry?.resource as { id?: string; name?: { family?: string; given?: string[] }[] } | undefined;
  return { id: resource?.id ?? '', name: `${resource?.name?.[0]?.given?.join(' ') ?? ''} ${resource?.name?.[0]?.family ?? ''}`.trim() };
});

const demoUsers = `${header('Demo users for local development. Password for all three: supabase-fhir')}
-- patient@example.com     sees only the first seeded patient (${patientIds[0]?.name})
-- clinician@example.com   reads and writes every seeded patient
-- admin@example.com       app_metadata.fhir_role = admin: everything, including the audit log

insert into auth.users
  (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
   raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
   confirmation_token, recovery_token, email_change_token_new, email_change)
values
  ('00000000-0000-0000-0000-000000000000', 'a0000000-0000-4000-8000-000000000001', 'authenticated', 'authenticated',
   'patient@example.com', extensions.crypt('supabase-fhir', extensions.gen_salt('bf')), now(),
   '{"provider":"email","providers":["email"],"fhir_role":"patient"}', '{}', now(), now(), '', '', '', ''),
  ('00000000-0000-0000-0000-000000000000', 'a0000000-0000-4000-8000-000000000002', 'authenticated', 'authenticated',
   'clinician@example.com', extensions.crypt('supabase-fhir', extensions.gen_salt('bf')), now(),
   '{"provider":"email","providers":["email"],"fhir_role":"practitioner"}', '{}', now(), now(), '', '', '', ''),
  ('00000000-0000-0000-0000-000000000000', 'a0000000-0000-4000-8000-000000000003', 'authenticated', 'authenticated',
   'admin@example.com', extensions.crypt('supabase-fhir', extensions.gen_salt('bf')), now(),
   '{"provider":"email","providers":["email"],"fhir_role":"admin"}', '{}', now(), now(), '', '', '', '')
on conflict (id) do nothing;

insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
select gen_random_uuid(), u.id, u.id::text,
       jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true),
       'email', now(), now(), now()
from auth.users u
where u.id in ('a0000000-0000-4000-8000-000000000001', 'a0000000-0000-4000-8000-000000000002', 'a0000000-0000-4000-8000-000000000003')
  and not exists (select 1 from auth.identities i where i.user_id = u.id);

insert into fhir.patient_access (user_id, patient_id, access_level, reason) values
  ('a0000000-0000-4000-8000-000000000001', '${patientIds[0]?.id}', 'read', 'patient portal: own record'),
${patientIds.map((p) => `  ('a0000000-0000-4000-8000-000000000002', '${p.id}', 'write', 'clinician: ${p.name}')`).join(',\n')}
on conflict (user_id, patient_id) do nothing;
`;

await mkdir(out, { recursive: true });
await writeFile(join(out, '10_synthea_providers.sql'), header(`Providers referenced by the seeded patients (${trimmed.length} resources)`) + sqlFor(providersBundle));
await writeFile(
  join(out, '20_synthea_patients.sql'),
  header(`${patientFiles.length} synthetic patients: ${patientIds.map((p) => p.name).join(', ')}`) +
    patientBundles.map((bundle, i) => `-- ${patientFiles[i]}\n${sqlFor(bundle)}`).join('\n'),
);
await writeFile(join(out, '30_demo_users.sql'), demoUsers);

console.log(`providers: ${trimmed.length} resources kept out of ${providerBundles.reduce((n, b) => n + (b.entry?.length ?? 0), 0)}`);
for (const [i, p] of patientIds.entries()) {
  console.log(`patient ${i + 1}: ${p.name} (${p.id}) from ${patientFiles[i]} with ${patientBundles[i]?.entry?.length} resources`);
}
