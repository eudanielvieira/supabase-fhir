#!/usr/bin/env bun
/**
 * Concatenates supabase/migrations/*.sql, in order, into sql/dist/supabase-fhir.sql so the
 * schema can be applied with any migration tool or plain psql (see sql/compat/ for Postgres
 * without Supabase). Run `bun run sql:build` after touching a migration; CI checks the result.
 */
import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const migrationsDir = 'supabase/migrations';
const target = 'sql/dist/supabase-fhir.sql';

const files = (await readdir(migrationsDir)).filter((f) => f.endsWith('.sql')).sort();
const parts = await Promise.all(files.map((f) => Bun.file(join(migrationsDir, f)).text()));

const banner = `-- =============================================================================
-- supabase-fhir | single-file distribution
-- Generated by scripts/build-sql.ts from:
${files.map((f) => `--   ${f}`).join('\n')}
-- On Supabase: apply as one migration. Elsewhere: run sql/compat/plain-postgres.sql first.
-- Do not edit by hand; change the migrations and run \`bun run sql:build\`.
-- =============================================================================

`;

await writeFile(target, banner + parts.map((p) => p.trimEnd() + '\n').join('\n'));
console.log(`${target}: ${files.length} migrations, ${(Buffer.byteLength(banner) + parts.reduce((n, p) => n + Buffer.byteLength(p), 0)) / 1024 | 0} KB`);
